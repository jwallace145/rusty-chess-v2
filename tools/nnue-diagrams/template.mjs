// The D2 source for one architecture snapshot, generated from its manifest.
//
// The diagram draws the engine's forward pass as modules, in the order the
// engine computes it (crates/search/src/nnue.rs, docs/nnue.md): the board's
// Chess768 features, each perspective's view of them (the own-king bucket
// and the file mirror, when the net has king buckets), the two perspective
// accumulators of one shared feature transformer, SCReLU, the concatenation
// of both perspectives' activations, the one output head the position's
// piece count selects (from a bank of B), and the scaling to centipawns.
// Nothing about training, data or runtime caching is drawn: a retrained net
// with the same topology gets the same picture under a different caption.

/** Colours by semantic role, one hue per stage, light fills with dark strokes. */
export const PALETTE = {
  input: { fill: "#DBEAFE", stroke: "#1D4ED8", text: "#1E3A8A" }, // blue: Chess768 input
  view: { fill: "#EDE9FE", stroke: "#6D28D9", text: "#4C1D95" }, // violet: king-bucket selection
  transformer: { fill: "#CFFAFE", stroke: "#0E7490", text: "#164E63" }, // cyan: shared feature transformer
  weights: { fill: "#A5F3FC", stroke: "#0E7490", text: "#164E63" }, // cyan, deeper: the one weight set both perspectives read
  activation: { fill: "#DCFCE7", stroke: "#15803D", text: "#14532D" }, // green: SCReLU
  head: { fill: "#FEF3C7", stroke: "#B45309", text: "#78350F" }, // amber: output bucket and head
  eval: { fill: "#FFE4E6", stroke: "#BE123C", text: "#881337" }, // rose: evaluation
  neutral: { fill: "#F8FAFC", stroke: "#475569", text: "#1E293B" },
  muted: { fill: "#F1F5F9", stroke: "#94A3B8", text: "#64748B" },
  edge: "#334155",
  edgeMuted: "#94A3B8",
};

/** A D2 double-quoted string. Manifest text never reaches D2 unquoted. */
export function d2String(s) {
  const text = String(s);
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if ((code < 0x20 && ch !== "\n") || code === 0x7f) throw new Error(`control character U+${code.toString(16).padStart(4, "0")} in a label`);
  }
  return `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")}"`;
}

const fmt = (n) => n.toLocaleString("en-US");

function classBlock(name, { fill, stroke, text }, extra = null) {
  const style = [`fill: ${d2String(fill)}`, `stroke: ${d2String(stroke)}`, `font-color: ${d2String(text)}`, "stroke-width: 2", "border-radius: 10"];
  if (extra !== null) style.push(extra);
  return `  ${name}: {\n    style: {\n${style.map((l) => `      ${l}`).join("\n")}\n    }\n  }`;
}

/**
 * The D2 source for `manifest` (a validated manifest from manifest.mjs).
 * Deterministic: the same manifest always gives the same text.
 */
export function d2Source(manifest) {
  const t = manifest.topology;
  const { hidden_width: H, king_buckets: K, output_buckets: B, features_per_perspective: F } = t;
  const { qa, qb, scale } = t.quantization;
  const twoH = 2 * H;
  const transformerWeights = F * K * H;

  const lines = [];
  const push = (s) => lines.push(s);

  push(`# ${manifest.net_id}: ${manifest.signature}`);
  push(`# Generated by tools/nnue-diagrams from docs/nnue-architectures/manifests/${manifest.net_id}.json. Do not edit by hand.`);
  push("direction: down");
  push("vars: {");
  push("  d2-config: {");
  push("    layout-engine: elk");
  push("    theme-id: 0");
  push("    pad: 24");
  push("  }");
  push("}");
  push("classes: {");
  push(classBlock("input", PALETTE.input));
  push(classBlock("view", PALETTE.view));
  push(classBlock("transformer", PALETTE.transformer));
  push(classBlock("weights", PALETTE.weights, "bold: true"));
  push(classBlock("activation", PALETTE.activation));
  push(classBlock("head", PALETTE.head));
  push(classBlock("eval", PALETTE.eval, "bold: true"));
  push(classBlock("neutral", PALETTE.neutral));
  push(classBlock("muted", PALETTE.muted, "stroke-dash: 4"));
  push(`  flow: { style: { stroke: ${d2String(PALETTE.edge)}; stroke-width: 2; font-color: ${d2String(PALETTE.edge)}; font-size: 14 } }`);
  push(`  faint: { style: { stroke: ${d2String(PALETTE.edgeMuted)}; stroke-width: 2; stroke-dash: 4; font-color: ${d2String(PALETTE.edgeMuted)}; font-size: 14 } }`);
  push(`  shared: { style: { stroke: ${d2String(PALETTE.transformer.stroke)}; stroke-width: 2; stroke-dash: 5; font-color: ${d2String(PALETTE.transformer.text)}; font-size: 14; bold: true } }`);
  push("}");
  push("");

  // Heading and caption, outside the flow.
  push(`title: ${d2String(`${manifest.net_id}\n${manifest.signature}`)} {`);
  push("  shape: text");
  push("  near: top-center");
  push(`  style: { font-size: 28; bold: true; font-color: ${d2String(PALETTE.neutral.text)} }`);
  push("}");
  push(`caption: ${d2String(`${manifest.featureTag}  ·  ${fmt(manifest.parameters)} parameters  ·  ${manifest.status_note}`)} {`);
  push("  shape: text");
  push("  near: bottom-center");
  push(`  style: { font-size: 16; font-color: ${d2String(PALETTE.muted.text)}; italic: true }`);
  push("}");
  push("");

  // 1. Input.
  push(`board: ${d2String(`Board position\nChess768: ${F} features per perspective\n2 colours × 6 piece kinds × 64 squares`)} { class: input }`);
  push("");

  // 2. Views (king buckets), one per perspective.
  if (K > 1) {
    push(`views: ${d2String(`Own-king view, one per perspective: ${K} king buckets`)} {`);
    push("  class: view");
    push("  style.font-size: 18");
    push(`  us: ${d2String(`Side to move's view\nits own king's bucket: ${t.king_bucket_layout}`)} { class: view }`);
    push(`  them: ${d2String(`Opponent's view\nits own king's bucket: ${t.king_bucket_layout}`)} { class: view }`);
    push("}");
  }
  push("");

  // 3. The shared feature transformer: one weight set, two perspective accumulators.
  push(`ft: ${d2String("Feature transformer: two perspectives, one shared weight set")} {`);
  push("  class: transformer");
  push("  style.font-size: 18");
  const weightsLabel =
    K > 1
      ? `Shared weights W\n${F} × ${K} → ${H}: ${fmt(transformerWeights)} weights + ${H} biases\n${K} slices of ${F} × ${H}, one per king bucket`
      : `Shared weights W\n${F} → ${H}: ${fmt(transformerWeights)} weights + ${H} biases`;
  push(`  w: ${d2String(weightsLabel)} { class: weights }`);
  push(`  us: ${d2String(`Side to move accumulator\n${F} → ${H}`)} { class: transformer }`);
  push(`  them: ${d2String(`Opponent accumulator\n${F} → ${H}`)} { class: transformer }`);
  push(`  w -> us: ${d2String("same W")} { class: shared }`);
  push(`  w -> them: ${d2String("same W")} { class: shared }`);
  push("}");
  push("");

  // 4. Activation and concatenation.
  push(`screlu: ${d2String(`SCReLU on every neuron\nclamp(x, 0, ${qa})²`)} { class: activation }`);
  push(`concat: ${d2String(`Concatenate: ${twoH} activations\n[side to move ${H} | opponent ${H}]`)} { class: neutral }`);
  push("");

  // 5. Output head(s): a bank of B, of which the piece count selects one.
  if (B > 1) {
    push(`select: ${d2String(`Output bucket from the board's piece count (2–32)\n${t.output_bucket_rule}  →  one of ${B}`)} { class: head }`);
    push(`heads: ${d2String(`Bank of ${B} output heads, ${twoH} → 1 each`)} {`);
    push("  class: head");
    push("  style.font-size: 18");
    push(`  chosen: ${d2String(`The one selected head\n${twoH} → 1: ${fmt(twoH)} weights + bias`)} { class: head }`);
    push(`  rest: ${d2String(`${B - 1} other heads\nnot evaluated for this position`)} { class: muted }`);
    push("}");
  } else {
    push(`head: ${d2String(`Single output head\n${twoH} → 1: ${fmt(twoH)} weights + bias`)} { class: head }`);
  }
  push("");

  // 6. Evaluation.
  push(`eval: ${d2String(`Evaluation in centipawns\n(Σ ÷ ${qa} + bias) × ${scale} ÷ (${qa} × ${qb}), side to move's view`)} { class: eval }`);
  push("");

  // Edges, in flow order.
  const headNode = B > 1 ? "heads.chosen" : "head";
  if (K > 1) {
    push(`board -> views.us: ${d2String("side to move's orientation")} { class: flow }`);
    push(`board -> views.them: ${d2String("opponent's orientation")} { class: flow }`);
    push(`views.us -> ft.us: ${d2String(`selects 1 of ${K} slices of W`)} { class: flow }`);
    push(`views.them -> ft.them: ${d2String(`selects 1 of ${K} slices of W`)} { class: flow }`);
  } else {
    push(`board -> ft.us: ${d2String("side to move's orientation")} { class: flow }`);
    push(`board -> ft.them: ${d2String("opponent's orientation")} { class: flow }`);
  }
  push(`ft.us -> screlu: ${d2String(`${H} pre-activations each`)} { class: flow }`);
  push("ft.them -> screlu: { class: flow }");
  push(`screlu -> concat: ${d2String(`${twoH} activations`)} { class: flow }`);
  if (B > 1) {
    push(`select -> heads.chosen: ${d2String("selects the head")} { class: flow }`);
    push(`concat -> heads.rest: ${d2String("not used")} { class: faint }`);
  }
  push(`concat -> ${headNode}: { class: flow }`);
  push(`${headNode} -> eval: ${d2String("one raw output")} { class: flow }`);

  return `${lines.join("\n")}\n`;
}
